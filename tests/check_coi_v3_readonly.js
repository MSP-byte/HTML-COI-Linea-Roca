'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8');
const marker='<script id="coi-v3-core">';
assert.equal(html.split(marker).length-1,1,'Un unico controlador COI V3');
assert.equal(html.split('<style id="coi-v3-ui-css">').length-1,1,'Estilos V3 unicos');
assert.ok(html.includes('readSheet:readGenericXlsx'),'Lector Excel independiente del esquema de Obras');
assert.ok(html.includes("const estacionRef=window.COI_REFDATA_ESTACIONES?.findByStation?.(s.nombre)"),'Tooltip utiliza catalogo y no nuevos aliases');
assert.ok(html.includes('Abreviatura: <b>'),'Tooltip muestra abreviatura');
const start=html.indexOf(marker),end=html.indexOf('</script>',start);
const js=html.slice(start+marker.length,end);
new Function(js);
assert.ok(js.includes("readOnly:true"),'Importador inicialmente read-only');
assert.ok(js.includes("if(!/^[\\d]{10}$/.test(r.oc))")||js.includes("if(!/^\\d{10}$/.test(r.oc))"),'Valida formato OC');
assert.ok(js.includes('Multifila')&&js.includes('Conflicto')&&js.includes('Sin cambios'),'Clasifica sin sobrescribir OC');
assert.ok(js.includes('coi_ordenes')&&js.includes('getSession'),'Conciliacion autorizada contra Supabase');
assert.ok(!/\.\s*(insert|upsert|update|delete|rpc)\s*\(/.test(js),'V3 no puede escribir contratos en esta fase');
assert.ok(!js.includes('localStorage.setItem('),'No guarda OC en localStorage');
assert.ok(js.includes('Monto OC (')&&js.includes('Importe contractual ('),'Finanzas discriminadas por moneda');
console.log('PASS COI V3: Excel, integridad contractual, tooltip y tableros sin escrituras');
