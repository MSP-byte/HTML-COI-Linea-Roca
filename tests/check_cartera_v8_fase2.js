'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const start='<script id="cartera-v8-p2-script">', end='</script>';
assert.equal(html.split(start).length-1,1,'One Cartera P2 script');
assert.equal(html.split('<style id="cartera-v8-p2-css">').length-1,1,'One Cartera P2 stylesheet');
const ix=html.indexOf(start),finish=html.indexOf(end,ix);
assert.ok(ix>0&&finish>ix);
const js=html.slice(ix+start.length,finish);
new vm.Script(js,{filename:'cartera-v8-p2.js'});
assert.match(js,/vistaCarteraObrasV8/);
assert.match(js,/cv2ChartEstado/);assert.match(js,/cv2ChartProveedor/);assert.match(js,/cv2ChartHitos/);
assert.match(js,/cv2File/);assert.match(js,/getRows/);
assert.match(js,/cv2OpenOC/);assert.match(js,/cv2GoMap/);
assert.match(js,/cv2-progress/);assert.match(js,/Sin dato/);
assert.ok(!/\.(?:insert|upsert|update|delete|rpc)\s*\(/.test(js),'Phase 2 must not write Supabase');
assert.ok(!/localStorage|sessionStorage/.test(js),'Phase 2 must not persist Excel outside Supabase');
assert.match(html,/coi:cartera-v8-updated/);
assert.match(html,/COI_CARTERA_V8_P2/);
console.log('PASS Cartera V8 fase 2: script, charts, data flow, read-only guard');
