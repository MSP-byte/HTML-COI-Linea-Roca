'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const marker='<script id="coi-referencias-estaciones-20261016">';
assert.equal(html.split(marker).length-1,1,'Única tabla ferroviaria de referencia');
assert.equal(html.split('<style id="coi-cartera-ux-20261016">').length-1,1,'Hoja de estilo única');
const pos=html.indexOf(marker),end=html.indexOf('</script>',pos);
const js=html.slice(pos+marker.length,end);
const win={};new vm.Script(js,{filename:'coi-referencias-estaciones.js'}).runInNewContext({window:win});
const ref=win.COI_REFDATA_ESTACIONES;
assert.ok(ref);
assert.equal(ref.records.length,50,'50 filas verificables del Excel');
assert.equal(ref.findByStation('Quilmes').codigo,'QL');
assert.equal(ref.findByStation('Villa Domínico').codigo,'LLD');
assert.equal(ref.findByStation('Plaza Constitución').codigo,'PC','Alias documentado');
assert.equal(ref.findByStation('Temperley').codigo,'TY');
assert.equal(ref.findByCode('ZZ').nombre,'Ezeiza');
assert.equal(ref.findByStation('Bosques'),null,'Bosque/Bosques sin normalización insegura');
assert.equal(ref.findByStation('Haedo'),null,'Ubicación no existente no se inventa');
assert.ok(ref.missing(['Quilmes','Cañuelas','Haedo']).join(',').includes('Cañuelas'));
assert.ok(/window\.COI_REFDATA_ESTACIONES\?\.render\?\.\(s\)/.test(html),'Ficha principal de Red Roca enlazada');
const phase='<script id="cartera-v8-p2-script">',p=html.indexOf(phase),z=html.indexOf('</script>',p);
const phaseJs=html.slice(p+phase.length,z);
new vm.Script(phaseJs,{filename:'cartera-v8-p2.js'});
assert.ok(phaseJs.includes('Identificación y ubicación'));
assert.ok(phaseJs.includes('Contratación y estado administrativo'));
assert.ok(phaseJs.includes('Fecha')&&phaseJs.includes('Date.UTC(1899,11,30)'));
assert.ok(phaseJs.includes('cv2-bar-top')&&phaseJs.includes('cv2-bar-values'));
assert.ok(!/\.(?:insert|upsert|update|delete|rpc)\s*\(/.test(phaseJs),'Sin escrituras contractuales');
console.log('PASS UX Cartera + 50 referencias ferroviarias; alias seguro; contraste y secciones');
