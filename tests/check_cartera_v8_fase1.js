'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');

const html = fs.readFileSync('index.html', 'utf8');
const cssMarker = '<style id="coi-cartera-v8-style">';
const scriptMarker = '<script id="coi-cartera-v8-fase1">';
assert.equal(html.split(cssMarker).length - 1, 1, 'Debe existir un unico estilo de Cartera');
assert.equal(html.split(scriptMarker).length - 1, 1, 'Debe existir un unico modulo Cartera');
const s = html.indexOf(scriptMarker);
const end = html.indexOf('</script>', s);
assert.ok(s > 0 && end > s, 'El modulo debe cerrarse');
const src = html.slice(s + scriptMarker.length, end);
new vm.Script(src, { filename: 'coi-cartera-v8-fase1.js' });
assert.match(src, /BASE_OBRAS/, 'Debe leer la hoja correcta');
assert.match(src, /\/\\.xlsx\$/i, 'Debe requerir la extension XLSX');
assert.match(src, /select\('nro_oc,estado_coi,id'\)/, 'Debe conciliar por SELECT con RLS');
assert.ok(!/\.insert\s*\(|\.update\s*\(|\.delete\s*\(|\.upsert\s*\(|\.rpc\s*\(/.test(src), 'El modulo no debe escribir a Supabase');
assert.ok(!/localStorage|sessionStorage/.test(src), 'No se persisten datos operativos en browser storage');
assert.match(src, /document\.createElement\('button'\)/, 'Navegacion integrada al menu');
assert.match(src, /addEventListener\('change'/, 'Selector de archivo con evento');
assert.match(src, /exportAudit/, 'Debe permitir exportar auditoria');
assert.match(src, /H1.H8/, 'Debe informar preservacion del circuito');
assert.match(src, /zipSelected|unzipSelected/, 'Debe leer XLSX sin biblioteca obligatoria');
console.log('PASS Cartera V8 fase 1: sintaxis, integracion, contrato de solo lectura');
